// ─── Templates ───────────────────────────────────────────────────────────────
export const templatesApi = {
  list: (params) => http.get('/v1/templates', { params }),
  get: (uid) => http.get(`/v1/templates/${uid}`),
  create: (data) => http.post('/v1/templates', data),
  update: (uid, data) => http.put(`/v1/templates/${uid}`, data),
  delete: (uid) => http.delete(`/v1/templates/${uid}`),
  copy: (uid) => http.post(`/v1/templates/${uid}/copy`),
  uploadThumbnail: (uid, file) => {
    const form = new FormData();
    form.append('thumbnail', file);
    return http.post(`/v1/templates/${uid}/thumbnail`, form, {
      headers: { 'Content-Type': 'multipart/form-data' },
    });
  },
  uploadAssets: (files) => {
    const form = new FormData();
    [...files].forEach((f) => form.append('files', f));
    return http.post('/v1/assets', form, { headers: { 'Content-Type': 'multipart/form-data' } });
  },
  categories: () => http.get('/v1/templates/categories'),
  createCategory: (data) => http.post('/v1/templates/categories', data),
  deleteCategory: (id) => http.delete(`/v1/templates/categories/${id}`),
};

